-- Lo que la app necesita y el esquema de Amanda todavía no guarda. Son tablas nuevas: las de Amanda
-- no cambian. Cada una cuelga de `alumnos` o `talleres` y se borra con ellos.

-- WhatsApp del alumno (10 dígitos). Uno por persona: la misma persona es un solo perfil.
CREATE TABLE alumnos_contacto (
	alumno_id INTEGER PRIMARY KEY REFERENCES alumnos (id) ON DELETE CASCADE,
	telefono TEXT NOT NULL UNIQUE CHECK (telefono ~ '^[0-9]{10}$')
);

-- Quien le ayuda a pagar: recibe el aviso de cobro por CoDi en su celular.
CREATE TABLE ayudantes (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	alumno_id INTEGER NOT NULL REFERENCES alumnos (id) ON DELETE CASCADE,
	nombre TEXT NOT NULL,
	parentesco TEXT NOT NULL,
	telefono TEXT NOT NULL CHECK (telefono ~ '^[0-9]{10}$'),
	UNIQUE (alumno_id, telefono)
);

-- La foto solo existe junto con el registro de quién dio permiso y cuándo.
CREATE TABLE fotos_alumno (
	alumno_id INTEGER PRIMARY KEY REFERENCES alumnos (id) ON DELETE CASCADE,
	uri TEXT NOT NULL,
	otorgado_por TEXT NOT NULL,
	otorgado_en TEXT NOT NULL DEFAULT ahora_texto()
);

-- Personas que pidieron lugar en un taller y esperan la aprobación de quien lo da.
CREATE TABLE solicitudes (
	alumno_id INTEGER NOT NULL REFERENCES alumnos (id) ON DELETE CASCADE,
	taller_id INTEGER NOT NULL REFERENCES talleres (id) ON DELETE CASCADE,
	estado TEXT NOT NULL CHECK (estado IN ('pending', 'waitlist')),
	creado_en TEXT NOT NULL DEFAULT ahora_texto(),
	PRIMARY KEY (alumno_id, taller_id)
);

-- Código que se comparte para pedir lugar; al cambiarlo, el anterior deja de servir.
CREATE TABLE codigos_inscripcion (
	taller_id INTEGER PRIMARY KEY REFERENCES talleres (id) ON DELETE CASCADE,
	codigo TEXT NOT NULL UNIQUE
);
